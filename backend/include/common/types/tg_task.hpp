#ifndef TASK_DISTRIBUTION_TASK_TAG_HPP
#define TASK_DISTRIBUTION_TASK_TAG_HPP

namespace td {
namespace types {
/** ---------------------------------------------------------------------------------------------------------
 * @brief The tg_task enum - метки задач (с приоритетами)
 -----------------------------------------------------------------------------------------------------------*/
enum class tg_task {
    _tg_unknown_    = 0x00,         /// <--- тип задачи неизвестен
    _tg_emergency_  = 0x01,         /// <--- тип задачи "авария" (приоритет наивысший)
    _tg_connection_ = 0x02,         /// <--- тип задачи "подключение" (приоритет средний)
    _tg_local_task_ = 0x04,         /// <--- тип задачи "локальная заявка" (наименьший приоритет)
    _tg_additional_order_ = 0x10    /// <--- тип задачи "дозаказ"
};

/** ---------------------------------------------------------------------------------------------------------
 * @brief The tg_status enum - метка задач по статусу выполнения
 -----------------------------------------------------------------------------------------------------------*/
enum class tg_status {
    _tg_unknown_ = 0x00,            /// <--- статус неизвестен
    _tg_free_ = 0x01,               /// <--- статус задачи "неназначена"
    _tg_work_ = 0x02,               /// <--- статус задачи "в работе"
    _tg_completed_ = 0x04           /// <--- статус задачи "выполнена"
};
}       /// <--- types
}   /// <--- td

#endif
